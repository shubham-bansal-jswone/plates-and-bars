#!/usr/bin/env bash
# Fails when `expo prebuild` output is committed (#980). `expo prebuild` generates
# apps/mobile/android/ and apps/mobile/ios/ from app.json and the config plugins, and it rewrites
# apps/mobile/package.json: @expo/cli's updatePkgScripts (prebuild/updatePackageJson.js) turns
# "android": "expo start --android" into "expo run:android" and "ios": "expo start --ios" into
# "expo run:ios", then writes the whole file back with JSON.stringify. Both are build output, not
# source: the native folders are ignored by apps/mobile/.gitignore and android-release.yml runs
# prebuild on a CI checkout. Re-check the rewrite when the Expo SDK moves.
# Run from the repository root. Usage: infra/scripts/check-prebuild-output.sh
set -euo pipefail
app="apps/mobile"
pkg="$app/package.json"
fail=0

# Tracked files stay tracked even when a rule ignores them, so `git ls-files` is what catches a
# commit of generated output (which is how it lands: added on a machine with no ignore rules).
tracked="$(git ls-files -- "$app/android" "$app/ios")"
if [ -n "$tracked" ]; then
  echo "::error::$app/android and $app/ios are generated by 'expo prebuild'; delete them and commit nothing under them"
  while IFS= read -r f; do printf '  %s\n' "$f"; done <<< "$tracked"
  fail=1
fi

# The package.json that prebuild writes. The file is flattened (every space and newline removed),
# so this matches a JSON key/value pair rather than one formatting: a re-indented or re-wrapped file
# cannot fail it, and the two values below are compared with their own spaces removed as well.
[ -f "$pkg" ] || { echo "::error::$pkg is missing"; exit 1; }
flat="$(tr -d '[:space:]' < "$pkg")"
for pair in 'android=expo run:android' 'ios=expo run:ios'; do
  key="${pair%%=*}"
  value="${pair#*=}"
  if [[ "$flat" == *"\"$key\":\"${value// /}\""* ]]; then
    echo "::error::$pkg has \"$key\": \"$value\": that is the value 'expo prebuild' writes over \"expo start --$key\" (#980)"
    fail=1
  fi
done

# The ignore rules are what keep prebuild output out of `git status` on a developer's machine, so
# losing them is a step towards committing it.
for dir in android ios; do
  if ! git check-ignore --no-index -q -- "$app/$dir/.gitignore"; then
    echo "::error::$app/$dir/ is not ignored; add /$dir/ to $app/.gitignore so prebuild output stays out of the history"
    fail=1
  fi
done

# The rules must stay anchored. An unanchored `android/` also ignores the native modules' own
# source (apps/mobile/modules/*/android/src/main/java/*.kt), so new Kotlin or Swift files there
# would vanish from `git status`. The paths are hypothetical, hence --no-index.
mod="$app/modules/x"
for path in "$mod/android/src/main/java/New.kt" "$mod/ios/New.swift"; do
  if git check-ignore --no-index -q -- "$path"; then
    dir="${path#"$mod"/}"
    dir="${dir%%/*}"
    echo "::error::$app/.gitignore ignores $path: anchor the rule as /$dir/ so native module sources under $app/modules/*/$dir/ stay visible to git"
    fail=1
  fi
done

[ "$fail" = 0 ] || exit 1
echo "no expo prebuild output committed"
