// Builds the synthetic landmark fixture (a made-up bodyweight squat, not a person) in the shape MediaPipe's world landmarks
// have: metres, origin at the hip centre of every frame, x right, y down, z away from the camera, plus noise, a camera yaw,
// and a short low-visibility gap with garbage coordinates. Deterministic (fixed pseudo-random generator).
// The committed fixture is this output; test/exercise-motion-pipeline.test.mjs checks they match.
// Usage: node exercise-motion/make-fixture.mjs   (rewrites fixtures/squat-synthetic.landmarks.json)
import { writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FORMAT, USED } from './pipeline.mjs';

const HEIGHT_M = 1.72;
const L = { neckHead: 0.13, spineNeck: 0.15, shoulder: 0.12, upperArm: 0.186, forearm: 0.146, hipHalf: 0.09, trunkUp: 0.15588, thigh: 0.245, shin: 0.246 };

// Sagittal-plane squat; phase 0 is standing, 1 is the bottom. Our axes: x left, y up, z forward.
function squatPose(phase, ankleY = 0.003) {
  const a = (phase * 28 * Math.PI) / 180;   // shin leans forward
  const b = (phase * 82 * Math.PI) / 180;   // thigh angle from vertical, going back
  const g = (phase * 32 * Math.PI) / 180;   // trunk leans forward
  const d = (phase * 80 * Math.PI) / 180;   // arms swing from hanging to forward
  const P = {};
  for (const [s, x] of [['l', 0.09], ['r', -0.09]]) {
    const ankle = [x, ankleY, 0];
    const knee = [x, ankle[1] + L.shin * Math.cos(a), ankle[2] + L.shin * Math.sin(a)];
    P[`${s}_ankle`] = ankle;
    P[`${s}_knee`] = knee;
    P[`${s}_hip`] = [x, knee[1] + L.thigh * Math.cos(b), knee[2] - L.thigh * Math.sin(b)];
  }
  const hips = [0, P.l_hip[1], P.l_hip[2]];
  const trunk = [0, Math.cos(g), Math.sin(g)];
  const spine = hips.map((v, i) => v + trunk[i] * L.trunkUp);
  const neck = spine.map((v, i) => v + trunk[i] * L.spineNeck);
  const headDir = [0, Math.cos(g / 2), Math.sin(g / 2)];
  const head = neck.map((v, i) => v + headDir[i] * L.neckHead);
  for (const [s, x] of [['l', 1], ['r', -1]]) {
    const sh = [neck[0] + x * L.shoulder, neck[1], neck[2]];
    const dir = [0, -Math.cos(d), Math.sin(d)];
    const el = sh.map((v, i) => v + dir[i] * L.upperArm);
    P[`${s}_shoulder`] = sh;
    P[`${s}_elbow`] = el;
    P[`${s}_wrist`] = el.map((v, i) => v + dir[i] * L.forearm);
  }
  P.head = head;
  P.l_ear = [head[0] + 0.07 / HEIGHT_M, head[1], head[2]];
  P.r_ear = [head[0] - 0.07 / HEIGHT_M, head[1], head[2]];
  return P;
}

function rng(seed) { let s = seed >>> 0; return () => { s = (Math.imul(s, 1664525) + 1013904223) >>> 0; return s / 4294967296 - 0.5; }; }

const NAMES = { 7: 'l_ear', 8: 'r_ear', 11: 'l_shoulder', 12: 'r_shoulder', 13: 'l_elbow', 14: 'r_elbow', 15: 'l_wrist', 16: 'r_wrist',
  23: 'l_hip', 24: 'r_hip', 25: 'l_knee', 26: 'r_knee', 27: 'l_ankle', 28: 'r_ankle' };

/** options: yawDeg (camera angle off a pure front view), fps, seconds, repSeconds, noise (metres) */
export function buildFixture({ yawDeg = 35, fps = 15, seconds = 3.2, repSeconds = 2.0, noise = 0.004 } = {}) {
  const rand = rng(1069);
  const yaw = (yawDeg * Math.PI) / 180, c = Math.cos(yaw), s = Math.sin(yaw);
  const n = Math.round(seconds * fps);
  const frames = [];
  for (let k = 0; k < n; k++) {
    const phase = 0.5 * (1 - Math.cos((2 * Math.PI * k) / (fps * repSeconds)));
    const P = squatPose(phase);
    const hips = [(P.l_hip[0] + P.r_hip[0]) / 2, (P.l_hip[1] + P.r_hip[1]) / 2, (P.l_hip[2] + P.r_hip[2]) / 2];
    const gap = k >= 20 && k <= 22;
    frames.push(USED.map((idx) => {
      const p = P[NAMES[idx]].map((v, i) => (v - hips[i]) * HEIGHT_M);
      // ours (x left, y up, z forward) to MediaPipe (x right-in-image, y down, z away from camera), then the camera yaw about the vertical
      const mx = p[0], my = -p[1], mz = -p[2];
      const xyz = [mx * c + mz * s, my, -mx * s + mz * c].map((v) => v + noise * rand());
      if (gap && idx === 15) return [0.9, 0.9, 0.9, 0.2];
      return [...xyz.map((v) => Math.round(v * 10000) / 10000), 0.9];
    }));
  }
  return { format: FORMAT, fps, indices: USED, note: 'Synthetic squat, not a person. Generated by make-fixture.mjs.', frames };
}

export function serializeFixture(fx) {
  const head = JSON.stringify({ ...fx, frames: '@F' }, null, 1);
  return `${head.replace('"@F"', `[\n${fx.frames.map((f) => ` ${JSON.stringify(f)}`).join(',\n')}\n ]`)}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = `${dirname(fileURLToPath(import.meta.url))}/fixtures/squat-synthetic.landmarks.json`;
  writeFileSync(out, serializeFixture(buildFixture()));
  console.log(`wrote ${out}`);
}
